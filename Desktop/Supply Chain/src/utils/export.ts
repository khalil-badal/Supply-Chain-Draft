export async function downloadPDF(
  rows: Record<string, string | number | null | undefined>[],
  columns: ExportColumn[],
  title: string,
  filename: string,
  meta: ExportMeta,
  landscape = true,
  statusHistoryCounts?: StatusHistoryCounts
): Promise<void> {
  const { jsPDF } = await import('jspdf');
  const { default: autoTable } = await import('jspdf-autotable');

  const doc = new jsPDF({
    orientation: landscape ? 'landscape' : 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const now = new Date();
  const dateStr = fmtDate(now.toISOString());
  const timeStr = fmtTime(now.toISOString());
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();

  const NAVY_RGB: [number, number, number] = [31, 56, 100];

  // ── Logo (top-left) ───────────────────────────────────────────────────────
  const logo = await loadLogoBase64();
  if (logo) {
    doc.addImage(logo, 'PNG', 10, 5, 32, 11);
  }

  // ── Title — most dominant element: bold, near-black, 17pt ────────────────
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(17);
  doc.setTextColor(17, 24, 39);
  doc.text(title, pageW / 2, 13, { align: 'center' });

  if (meta.dateRange) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(meta.dateRange, pageW / 2, 18, { align: 'center' });
  }

  // ── Top-right: generated by ───────────────────────────────────────────────
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(148, 163, 184);
  doc.text(
    `Generated by ${meta.generatedByName} (${meta.generatedByRole})`,
    pageW - 10, 8, { align: 'right' }
  );
  doc.text(`${dateStr}  at  ${timeStr}`, pageW - 10, 12.5, { align: 'right' });

  // ── Navy horizontal rule ──────────────────────────────────────────────────
  const headerEndY = meta.dateRange ? 23 : 20;
  doc.setDrawColor(...NAVY_RGB);
  doc.setLineWidth(0.5);
  doc.line(10, headerEndY, pageW - 10, headerEndY);

  // ── Status history summary table ──────────────────────────────────────────
  let mainTableStartY = headerEndY + 3;
  if (statusHistoryCounts) {
    const summaryBody = STATUS_ORDER.map(s => [
      s,
      String(statusHistoryCounts.ever_held[s] ?? 0),
      String(statusHistoryCounts.current[s] ?? 0),
    ]);
    summaryBody.push(['Total Records', String(statusHistoryCounts.total_records), String(statusHistoryCounts.total_records)]);

    autoTable(doc, {
      head: [['Status', 'Ever Held', 'Current Status']],
      body: summaryBody,
      startY: headerEndY + 3,
      margin: { left: 10, right: 10 },
      tableWidth: 120,
      styles: { fontSize: 8, cellPadding: { top: 2, right: 4, bottom: 2, left: 4 } },
      headStyles: { fillColor: NAVY_RGB, textColor: [255, 255, 255], fontStyle: 'bold', halign: 'center' },
      columnStyles: {
        0: { halign: 'left', fontStyle: 'bold' },
        1: { halign: 'center' },
        2: { halign: 'center' },
      },
      didDrawPage: () => {},
    });

    const summaryFinalY = (doc as any).lastAutoTable?.finalY ?? headerEndY + 30;
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(6.5);
    doc.setTextColor(100, 116, 139);
    doc.text(
      '* Ever Held counts may exceed total records as one record can pass through multiple statuses over its lifetime.',
      10, summaryFinalY + 4
    );
    mainTableStartY = summaryFinalY + 10;
  }

  // ── Pill column index set ─────────────────────────────────────────────────
  const pillCols = new Set<number>(
    columns.reduce<number[]>((acc, col, i) => { if (col.pdfPill) acc.push(i); return acc; }, [])
  );

  // ── Table ─────────────────────────────────────────────────────────────────
  // jsPDF's built-in Helvetica uses WinAnsi encoding; U+20B1 (₱) is not in
  // the charset and gets mapped to 0xB1 (±), which also corrupts the internal
  // text-width metrics and causes adjacent text (e.g. ".00") to be clipped.
  // Replace ₱ with the ISO-safe "PHP " prefix for all PDF cell values.
  const pdfSafe = (v: string | number | null | undefined) =>
    v == null ? '' : String(v).replace(/₱/g, 'PHP ');

  const tableBody = rows.map(r =>
    columns.map(c => pdfSafe(r[c.key]))
  );

  autoTable(doc, {
    head: [columns.map(c => c.header)],
    body: tableBody,
    startY: mainTableStartY,
    margin: { left: 10, right: 10 },
    tableWidth: 'auto',
    styles: {
      fontSize: 8,
      cellPadding: { top: 2.5, right: 3.5, bottom: 2.5, left: 3.5 },
      lineColor: [226, 232, 240],
      lineWidth: 0.2,
      overflow: 'linebreak',
    },
    headStyles: {
      fillColor: NAVY_RGB,
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8,
      halign: 'center',
      valign: 'middle',
      minCellHeight: 9,
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    bodyStyles: {
      textColor: [30, 41, 59],
      minCellHeight: 9,
      valign: 'middle',
    },
    columnStyles: Object.fromEntries(
      columns.map((col, i) => [i, {
        cellWidth: col.pdfWidth ?? 'auto',
        halign: col.pdfAlign ?? (pillCols.has(i) ? 'center' : 'left'),
      }])
    ),
    // Suppress default text for pill cells so we can draw the badge manually
    willDrawCell: (data: any) => {
      if (data.section === 'body' && pillCols.has(data.column.index)) {
        data.cell.text = [];
      }
    },
    // Draw colored status pills
    didDrawCell: (data: any) => {
      if (data.section !== 'body' || !pillCols.has(data.column.index)) return;
      const text = String(data.cell.raw ?? '').trim();
      if (!text) return;
      const color: [number, number, number] = PILL_COLORS[text.toLowerCase()] ?? [107, 114, 128];
      const cw = data.cell.width;
      const ch = data.cell.height;
      const cx = data.cell.x;
      const cy = data.cell.y;
      const pillW = Math.min(cw - 6, 32);
      const pillH = 5.5;
      const pillX = cx + (cw - pillW) / 2;
      const pillY = cy + (ch - pillH) / 2;
      doc.setFillColor(color[0], color[1], color[2]);
      doc.roundedRect(pillX, pillY, pillW, pillH, 1.4, 1.4, 'F');
      doc.setTextColor(255, 255, 255);
      doc.setFontSize(6.5);
      doc.setFont('helvetica', 'bold');
      doc.text(text, pillX + pillW / 2, pillY + pillH / 2 + 0.4, {
        align: 'center',
        baseline: 'middle',
      });
      // Reset font for subsequent cells
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(30, 41, 59);
    },
    rowPageBreak: 'avoid',
    didDrawPage: (data: any) => {
      const pageCount = (doc as any).internal.getNumberOfPages();
      const currentPage = data.pageNumber;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(7.5);
      doc.setTextColor(148, 163, 184);
      doc.text(`${dateStr} at ${timeStr}`, 10, pageH - 5);
      doc.text('Microgenesis Business Systems — Confidential', pageW / 2, pageH - 5, { align: 'center' });
      doc.text(`Page ${currentPage} of ${pageCount}`, pageW - 10, pageH - 5, { align: 'right' });

      if (currentPage > 1) {
        doc.setDrawColor(...NAVY_RGB);
        doc.setLineWidth(0.3);
        doc.line(10, 8, pageW - 10, 8);
      }
    },
  });

  // ── Total count after table ───────────────────────────────────────────────
  const finalY = (doc as any).lastAutoTable?.finalY ?? headerEndY + 10;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(...NAVY_RGB);
  doc.text(`Total Records: ${rows.length}`, 10, finalY + 6);

  doc.save(`${filename}-${now.toISOString().split('T')[0]}.pdf`);
}

