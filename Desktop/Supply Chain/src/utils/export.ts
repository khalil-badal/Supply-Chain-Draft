/**
 * Shared export utilities — CSV, Excel (exceljs, styled), PDF (jspdf + autotable).
 * All three formats follow the Microgenesis Export Formatting Standard:
 *   - 3-row metadata header before data
 *   - Navy (#1F3864) header row, white bold text
 *   - Title-Case column headers, no snake_case
 *   - Date: "Jul 17, 2026" | Time: "9:32 AM"
 *   - Footer row with total count
 */

export interface ExportColumn {
  header: string;
  key: string;
  width?: number;         // Excel column width (chars)
  pdfWidth?: number;      // PDF column width (mm); omit for auto
  pdfPill?: boolean;      // Render cell as a colored status pill in PDF
  pdfAlign?: 'left' | 'center' | 'right';
}

export interface ExportMeta {
  reportName: string;
  dateRange?: string;
  generatedByName: string;
  generatedByRole: string;
}

export interface StatusHistoryCounts {
  ever_held: Record<string, number>;
  current: Record<string, number>;
  total_records: number;
}

// ─── Formatters ───────────────────────────────────────────────────────────────

export function fmtDate(s: string | null | undefined): string {
  if (!s) return '';
  const d = new Date(s.includes('T') ? s : `${s}T12:00:00`);
  if (isNaN(d.getTime())) return s;
  return d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
}

export function fmtTime(s: string | null | undefined): string {
  if (!s) return '';
  const d = new Date(s);
  if (isNaN(d.getTime())) return '';
  return d.toLocaleTimeString('en-US', { hour: 'numeric', minute: '2-digit', hour12: true });
}

export function fmtDatetime(s: string | null | undefined): string {
  if (!s) return '';
  const date = fmtDate(s);
  const time = fmtTime(s);
  return date && time ? `${date} ${time}` : date || time;
}

export function fmtStatus(s: string | null | undefined): string {
  if (!s) return '';
  return s.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
}

export function fmtCurrency(n: number | null | undefined): string {
  if (n == null) return '';
  return '₱' + n.toLocaleString('en-PH', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

// ─── CSV Export ───────────────────────────────────────────────────────────────

const STATUS_ORDER = ['Scheduled', 'Delivered', 'Pending', 'On-Hold', 'Rescheduled'] as const;

export function downloadCSV(
  rows: Record<string, string | number | null | undefined>[],
  columns: ExportColumn[],
  filename: string,
  meta: ExportMeta,
  statusHistoryCounts?: StatusHistoryCounts
): void {
  const now = new Date();
  const dateStr = fmtDate(now.toISOString());
  const timeStr = fmtTime(now.toISOString());
  const reportLine = meta.dateRange
    ? `${meta.reportName} — ${meta.dateRange}`
    : meta.reportName;

  const metaRows = [
    ['Microgenesis Business Systems'],
    [reportLine],
    [`Generated by: ${meta.generatedByName} (${meta.generatedByRole}) on ${dateStr} at ${timeStr}`],
    []
  ];

  const summaryRows: string[][] = [];
  if (statusHistoryCounts) {
    summaryRows.push(['STATUS HISTORY SUMMARY']);
    summaryRows.push([
      'Status',
      'Ever Held (historical — records counted in each status they passed through)',
      'Current Status (each record counted once)'
    ]);
    for (const s of STATUS_ORDER) {
      summaryRows.push([s, String(statusHistoryCounts.ever_held[s] ?? 0), String(statusHistoryCounts.current[s] ?? 0)]);
    }
    summaryRows.push(['Total Records', String(statusHistoryCounts.total_records), String(statusHistoryCounts.total_records)]);
    summaryRows.push(['* Ever Held counts may exceed total records as one record can pass through multiple statuses over its lifetime.']);
    summaryRows.push([]);
  }

  const headerRow = columns.map(c => c.header);

  const dataRows = rows.map(r =>
    columns.map(c => {
      const v = r[c.key];
      return v == null ? '' : String(v);
    })
  );

  const footerRow = [`Total Records: ${rows.length}`, ...Array(columns.length - 1).fill('')];

  const allRows = [...metaRows, ...summaryRows, headerRow, ...dataRows, footerRow];

  const csv = allRows
    .map(row => row.map(cell => `"${String(cell).replace(/"/g, '""')}"`).join(','))
    .join('\r\n');

  const blob = new Blob(['﻿' + csv, { type: 'text/csv;charset=utf-8;' }] as unknown as BlobPart[]);
  const url = URL.createObjectURL(new Blob(['﻿' + csv], { type: 'text/csv;charset=utf-8;' }));
  const a = document.createElement('a');
  a.href = url;
  a.download = `${filename}-${now.toISOString().split('T')[0]}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

// ─── Excel Export (exceljs — styled) ─────────────────────────────────────────

const NAVY = 'FF1F3864';
const WHITE = 'FFFFFFFF';
const GRAY_ROW = 'FFF8F9FA';

const STATUS_EXCEL_COLORS: Record<string, string> = {
  'Scheduled':   'FF2563EB',
  'Delivered':   'FF059669',
  'Pending':     'FFD97706',
  'On-Hold':     'FFDC2626',
  'Rescheduled': 'FF7C3AED',
};

export async function downloadExcel(
  rows: Record<string, string | number | null | undefined>[],
  columns: ExportColumn[],
  sheetName: string,
  filename: string,
  meta: ExportMeta,
  statusHistoryCounts?: StatusHistoryCounts
): Promise<void> {
  const ExcelJS = (await import('exceljs')).default;
  const wb = new ExcelJS.Workbook();
  wb.creator = meta.generatedByName;
  wb.created = new Date();

  const ws = wb.addWorksheet(sheetName);

  const now = new Date();
  const dateStr = fmtDate(now.toISOString());
  const timeStr = fmtTime(now.toISOString());
  const reportLine = meta.dateRange
    ? `${meta.reportName} — ${meta.dateRange}`
    : meta.reportName;

  // ── Row 1: Company name ───────────────────────────────────────────────────
  const r1 = ws.addRow(['Microgenesis Business Systems']);
  r1.getCell(1).font = { bold: true, size: 14, color: { argb: NAVY } };

  // ── Row 2: Report name + date range ──────────────────────────────────────
  const r2 = ws.addRow([reportLine]);
  r2.getCell(1).font = { size: 11, color: { argb: NAVY } };

  // ── Row 3: Generated by ───────────────────────────────────────────────────
  const r3 = ws.addRow([
    `Generated by: ${meta.generatedByName} (${meta.generatedByRole}) on ${dateStr} at ${timeStr}`
  ]);
  r3.getCell(1).font = { size: 10, italic: true, color: { argb: 'FF64748B' } };

  // ── Row 4: Blank ─────────────────────────────────────────────────────────
  ws.addRow([]);

  // ── Summary table (rows 5–14 when present) ────────────────────────────────
  let summaryRowCount = 0;
  if (statusHistoryCounts) {
    // Title row
    const sTitle = ws.addRow(['STATUS HISTORY SUMMARY']);
    sTitle.getCell(1).font = { bold: true, size: 11, color: { argb: NAVY } };
    sTitle.height = 18;

    // Header row
    const sHeader = ws.addRow(['Status', 'Ever Held', 'Current Status']);
    sHeader.eachCell((cell, col) => {
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: NAVY } };
      cell.font = { bold: true, color: { argb: WHITE }, size: 10 };
      cell.alignment = { vertical: 'middle', horizontal: col === 1 ? 'left' : 'center' };
      cell.border = {
        top: { style: 'thin', color: { argb: NAVY } },
        bottom: { style: 'thin', color: { argb: NAVY } },
        left: { style: 'thin', color: { argb: 'FFD0D0D0' } },
        right: { style: 'thin', color: { argb: 'FFD0D0D0' } }
      };
    });
    sHeader.height = 18;

    // Status rows
    for (const s of STATUS_ORDER) {
      const sRow = ws.addRow([s, statusHistoryCounts.ever_held[s] ?? 0, statusHistoryCounts.current[s] ?? 0]);
      const color = STATUS_EXCEL_COLORS[s] ?? NAVY;
      sRow.getCell(1).font = { bold: true, color: { argb: color }, size: 10 };
      sRow.getCell(2).alignment = { horizontal: 'center' };
      sRow.getCell(3).alignment = { horizontal: 'center' };
      sRow.eachCell({ includeEmpty: true }, cell => {
        cell.border = {
          bottom: { style: 'hair', color: { argb: 'FFE2E8F0' } },
          left: { style: 'thin', color: { argb: 'FFE2E8F0' } },
          right: { style: 'thin', color: { argb: 'FFE2E8F0' } }
        };
      });
      sRow.height = 16;
    }

    // Total row
    const sTot = ws.addRow(['Total Records', statusHistoryCounts.total_records, statusHistoryCounts.total_records]);
    sTot.getCell(1).font = { bold: true, size: 10, color: { argb: NAVY } };
    sTot.getCell(2).font = { bold: true, size: 10 };
    sTot.getCell(2).alignment = { horizontal: 'center' };
    sTot.getCell(3).font = { bold: true, size: 10 };
    sTot.getCell(3).alignment = { horizontal: 'center' };
    sTot.getCell(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFEEF2FF' } };
    sTot.getCell(2).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFEEF2FF' } };
    sTot.getCell(3).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFEEF2FF' } };
    sTot.height = 16;

    // Footnote
    const sNote = ws.addRow(['* Ever Held counts may exceed total records as one record can pass through multiple statuses over its lifetime.']);
    sNote.getCell(1).font = { italic: true, size: 8, color: { argb: 'FF64748B' } };
    sNote.height = 14;

    // Blank separator
    ws.addRow([]);

    // 1 title + 1 header + 5 status + 1 total + 1 footnote + 1 blank = 10
    summaryRowCount = 10;
  }

  // ── Column headers ────────────────────────────────────────────────────────
  const headerRow = ws.addRow(columns.map(c => c.header));
  headerRow.eachCell(cell => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: NAVY } };
    cell.font = { bold: true, color: { argb: WHITE }, size: 10 };
    cell.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true };
    cell.border = {
      top: { style: 'thin', color: { argb: NAVY } },
      bottom: { style: 'thin', color: { argb: NAVY } },
      left: { style: 'thin', color: { argb: 'FFD0D0D0' } },
      right: { style: 'thin', color: { argb: 'FFD0D0D0' } }
    };
  });
  headerRow.height = 22;

  // ── Data rows ─────────────────────────────────────────────────────────────
  rows.forEach((r, idx) => {
    const dataRow = ws.addRow(columns.map(c => {
      const v = r[c.key];
      return v == null ? '' : v;
    }));
    const isAlt = idx % 2 === 1;
    dataRow.eachCell({ includeEmpty: true }, cell => {
      if (isAlt) {
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: GRAY_ROW } };
      }
      cell.font = { size: 10 };
      cell.border = {
        bottom: { style: 'hair', color: { argb: 'FFE2E8F0' } },
        left: { style: 'thin', color: { argb: 'FFE2E8F0' } },
        right: { style: 'thin', color: { argb: 'FFE2E8F0' } }
      };
      cell.alignment = { vertical: 'middle', wrapText: false };
    });
    dataRow.height = 18;
  });

  // ── Footer row ────────────────────────────────────────────────────────────
  const footerRow = ws.addRow([`Total Records: ${rows.length}`]);
  footerRow.getCell(1).font = { bold: true, italic: true, size: 10, color: { argb: NAVY } };
  footerRow.getCell(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFEEF2FF' } };

  // ── Column widths ─────────────────────────────────────────────────────────
  ws.columns = columns.map(c => ({
    width: Math.max(c.width ?? 18, c.header.length + 4)
  }));

  // ── Merge meta rows across all columns ───────────────────────────────────
  const colCount = columns.length;
  if (colCount > 1) {
    ws.mergeCells(1, 1, 1, colCount);
    ws.mergeCells(2, 1, 2, colCount);
    ws.mergeCells(3, 1, 3, colCount);
    if (summaryRowCount > 0) {
      // Merge summary title and footnote across all columns
      ws.mergeCells(5, 1, 5, colCount);
      ws.mergeCells(5 + 1 + STATUS_ORDER.length + 2, 1, 5 + 1 + STATUS_ORDER.length + 2, colCount);
    }
    const footerRowNum = 4 + summaryRowCount + 1 + rows.length + 1;
    ws.mergeCells(footerRowNum, 1, footerRowNum, colCount);
  }

  // ── Download ──────────────────────────────────────────────────────────────
  const buffer = await wb.xlsx.writeBuffer();
  const blob = new Blob([buffer], {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${filename}-${now.toISOString().split('T')[0]}.xlsx`;
  a.click();
  URL.revokeObjectURL(url);
}

// ─── PDF Export (jspdf + jspdf-autotable) ────────────────────────────────────

async function loadLogoBase64(): Promise<string | null> {
  try {
    const res = await fetch('/microgenesis_logo.png');
    if (!res.ok) return null;
    const blob = await res.blob();
    return new Promise(resolve => {
      const reader = new FileReader();
      reader.onload = () => resolve(reader.result as string);
      reader.onerror = () => resolve(null);
      reader.readAsDataURL(blob);
    });
  } catch {
    return null;
  }
}

